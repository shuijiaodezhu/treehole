'use client'

/**
 * 小现代诗 —— 给首页那封信用的
 *
 * 为什么不再从"每日一句"里抽三句：
 *   那些句子是彼此独立的（"今天也要好好吃饭啊" / "慢一点，没关系"），
 *   三句并排只是三句话 ✗ 不是一首诗。
 *   这里每一首都是**第一句起意、其余是它的延伸**，读下来是一口气 ✓
 *
 * 写法上的分寸：
 *   · 3~4 行，每行都很短 —— 信纸上的诗不该长
 *   · 不押韵、不用大词、不劝人 —— 只把一句话说慢一点
 *   · 主语尽量是"我"或"我们"，不是"你要…"（命令句最伤温度）
 */

const LITTLE_POEMS: string[][] = [
  ['今天也是限量版。', '你不能再来一次，', '所以慢一点也没关系。'],
  ['难过是可以的。', '不用解释，也不用急着好起来，', '我在这儿坐一会儿。'],
  ['记得吃早餐。', '哪怕只是两口，', '也算你好好待过自己。'],
  ['回家的路上注意安全。', '灯我留着，', '门也不锁。'],
  ['今天有星星吗。', '没有也没关系，', '我知道你抬过头了。'],
  ['你已经很努力了。', '今天做不到的那些，', '明天还是你的。'],
  ['有人为你留了灯。', '不是等你交差，', '是等你回来。'],
  ['慢一点，没关系。', '世界不会跑，', '跑的是我们自己的心。'],
  ['想说什么就说吧。', '说错了也不要紧，', '这里没有人记账。'],
  ['天冷了，记得穿厚一点。', '我这边也冷了，', '所以我们算是一起冷着。'],
  ['不用成为别人。', '你把自己照顾好，', '就已经很好了。'],
  ['写下来，就不算憋着。', '纸是最能保守秘密的，', '我也是。'],
]

/** 一天一首：按日期取，同一天内稳定；换日才换诗 */
export function getDailyPoem(now: number = Date.now()): string[] {
  const day = Math.floor(now / (1000 * 60 * 60 * 24))
  return LITTLE_POEMS[day % LITTLE_POEMS.length]
}
